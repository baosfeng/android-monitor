package com.bsfeng.monitor.autobook

// 从 autobook/AutoBookParser.kt 拆出：解析用到的正则、词表与标签。
// 纯常量数据；改这里等于改识别口径，改前先看 AutoBookParserTest。

/** 账单识别的正则与词表（AutoBookParser 使用的全部模式数据）。 */
internal object AutoBookPatterns {

    /** 一屏出现多少处交易痕迹就判定为「列表页」（单笔账单页只会出现 1 处） */
    const val MULTI_TRANSACTION_THRESHOLD = 2

    /** 带方向前缀的金额：`支出3元` / `已支付 ¥12.34` / `收入 5.00 元` */
    val PREFIXED_AMOUNT = Regex(
        "(支出|收入|转出|转入|消费|收款|付款|支付|已支付|已收款|扣款|还款)\\s*[¥￥]?\\s*([0-9]{1,3}(?:,[0-9]{3})*(?:\\.[0-9]{1,2})?|[0-9]+(?:\\.[0-9]{1,2})?)\\s*元?"
    )

    /** 带货币符号的金额（微信通知只认这种） */
    val SYMBOL_AMOUNT = Regex("[¥￥]\\s*([0-9]{1,3}(?:,[0-9]{3})*(?:\\.[0-9]{1,2})?|[0-9]+(?:\\.[0-9]{1,2})?)")

    /** 带「元」的金额（支付宝通知常见） */
    val YUAN_AMOUNT = Regex("([0-9]{1,3}(?:,[0-9]{3})*(?:\\.[0-9]{1,2})?|[0-9]+(?:\\.[0-9]{1,2})?)\\s*元")

    /** 裸金额：仅用于详情页的大号金额（如 `-3.00`），必须带两位小数 */
    val PLAIN_AMOUNT = Regex("(?:^|\\s)(-?)([0-9]{1,3}(?:,[0-9]{3})*\\.[0-9]{2})(?:\\s|$)")

    /**
     * 时间戳（`20:47` / `23:14:43`）。
     *
     * ⚠️ 真机事故（2026-10-17 微信首页）：`微信支付 20:47` 这行被 [PREFIXED_AMOUNT] 的
     * 「支付」前缀命中，小时数 `20` 被当成金额 —— 首页于是「识别出一笔收入 ¥20.00」。
     * 金额提取前先抹掉时间戳：时间永远不是金额。
     */
    val CLOCK = Regex("(?<!\\d)\\d{1,2}:\\d{2}(?::\\d{2})?(?!\\d)")

    /** 明确的收入语义 */
    val INCOME_WORDS = listOf("收款", "到账", "收入", "退款", "已收", "退还", "返现", "入账")

    /** 明确的支出语义 */
    val EXPENSE_WORDS = listOf("付款", "支付", "消费", "转出", "已付", "扣款", "还款", "支出", "提现")

    /**
     * 方向词出现在**标签 / 提示语**里时先抹掉，否则整页方向会判反。
     *
     * 真机事故（2026-10-17，支付宝转账成功页）：页面是
     * `转账成功￥0.01 回首页 | 转账成功 | 0.01 | 收款方 张三(***) | 交易方式 余额宝(转出资金付款) | 完成`。
     * 「收款方」是**收款人标签**（这笔钱是用户付出去的），但 [INCOME_WORDS] 里的「收款」先命中、
     * 且位置早于「转出资金付款」里的「付款」，于是整笔被记成**收入**。
     *
     * 这些词只做标签，不表达方向，必须在判定前替换掉。
     */
    val DIRECTION_LABEL_NOISE = listOf(
        "收款方", "付款方", "收款人", "付款人", "收款账户", "付款账户",
        "付款方式", "收款方式", "交易方式"
    )

    /**
     * 付款方视角的「等待对方确认收款」提示（微信转账成功页：`待李四确认收款`）。
     *
     * 这里面的「收款」描述的是**对方**的动作，不是用户收入；不抹掉会把支出判成收入。
     * ⚠️ 不能只抹「确认收款」：收款方自己点「确认收款」时那是真收入。
     */
    val PENDING_RECEIPT = Regex("待.{0,15}?确认收款")

    /** 品牌名清洗表：这些词含「支付/收款」二字，判定方向前先抹掉（否则「支付宝 | 20元」被记成支出） */
    val BRAND_WORDS = listOf("支付宝", "微信支付", "微信", "云闪付", "财付通", "银联", "数字人民币")

    /** 未来时态：命中即放弃整条（活动预告、待扣款提醒都不是已发生的交易） */
    val FUTURE_WORDS = listOf("将于", "即将", "预计", "明日", "待扣", "待支付", "续费提醒", "请及时", "最后提醒")

    /**
     * 账户间转移：提现/充值不是收支，记了会让总身家凭空变化。
     *
     * ⚠️ 必须用**贴住金额的完整词组**，不能用「提现」两个字：支付宝收款通知的尾巴上就带着
     * 「享免费提现等更多专属服务」，只判两个字会把真实收款整条丢掉（有单测覆盖）。
     */
    val TRANSFER_SKIP_WORDS = listOf(
        "提现到", "提现成功", "提现金额", "提现-", "充值成功", "充值到账", "转入零钱通", "转出到余额"
    )

    /**
     * 非交易文本：验证码、营销、优惠券等。
     *
     * ⚠️ 只允许在**金额所在行**上判定，不能拿来做整页排除 —— 真机支付宝账单详情页底部就有
     * 「支付奖励 立即领取2积分」，整页排除会让一笔真实支出被漏掉。
     */
    val NOISE_WORDS = listOf("验证码", "优惠券", "立减", "满减", "广告", "恭喜获得")

    /**
     * 金额候选要排除的上下文（余额 / 额度 / 优惠 / 价格都不是交易金额）。
     *
     * ⚠️ 价格类标签（订单金额 / 商品金额 / 订单总额 / 商品总价 / 订单价格 / 商品单价 / 原价）必须在这里：
     * 同一张支付宝账单详情页会同时出现「订单金额 50.00（原价）」与「支出49.9元（实付）」，
     * 价格行不是交易金额，也**不参与一屏多笔计数**（[AutoBookGate.hasMultipleTransactions] 数不同金额），
     * 否则单笔账单页会因为「实付 + 原价」两个金额被判成流水列表、整笔漏记。
     *
     * ⚠️ 不能加「支付金额 / 付款金额 / 实付」：那是真实交易金额，加进来会抹掉金额行。
     */
    val AMOUNT_NOISE = listOf(
        "余额", "额度", "限额", "可用", "积分", "优惠", "抵扣", "手续费", "剩余", "冻结", "红包", "立减",
        // 价格 / 原价类字段：不是交易金额，也不参与一屏多笔计数
        "原价", "订单金额", "商品金额", "订单总额", "商品总价", "订单价格", "商品单价"
    )

    /**
     * 商户名标签：命中后取同一行右侧内容。
     *
     * ⚠️ 这里**不放「付款方」**：它是「付款方式」的前缀，会从 `付款方式 招商银行信用卡(8888)`
     * 这行取出「式 招商银行信用卡(8888)」当商户名（真机实测踩到）。而且付款方是转账的转出方，
     * 本来也不是商户。
     */
    val MERCHANT_LABELS = listOf(
        "收款方全称", "商户全称", "商户名称", "收款方", "交易对方", "对方", "商家", "店铺", "商户"
    )

    /**
     * 账户（付款方式）标签。
     *
     * ⚠️ 不要把「零钱」「余额宝」这类**值**放进来：标签表同时用于「排除值看起来像标签」的判断，
     * 放进来会让「支付方式 零钱」取不到值（真机/单测都踩过）。
     */
    val ACCOUNT_LABELS = listOf(
        "付款方式", "支付方式", "付款账户", "支付账户", "扣款方式", "付款渠道",
        // 支付宝支付成功页的付款方式标签
        "交易方式"
    )

    /** 交易时间标签 */
    val TIME_LABELS = listOf("支付时间", "交易时间", "付款时间", "创建时间", "转账时间")

    /** 平台分类标签（支付宝/微信自带分类，如「日用百货」） */
    val CATEGORY_LABELS = listOf("账单分类", "交易分类", "分类")

    /**
     * 商品说明标签。
     *
     * 真机实测（支付宝账单详情页）：`商品说明 某某湘菜馆(示例店)外卖订单` ——
     * 这是整页**对账信息量最大**的字段（商户名常常只是平台名，如「淘宝闪购」）。
     * 顺序有讲究：`商品说明` 必须排在 `商品` 前面，否则被短标签抢占。
     */
    val PRODUCT_LABELS = listOf("商品说明", "订单说明", "交易说明", "商品")

    /** 商品说明保留长度：商品名可能很长，超出截断 */
    const val PRODUCT_DESC_MAX_LENGTH = 40

    /** 页面交易时间的两种格式（ISO / 中文年月日），见 [normalizeTradeTime] */
    val TRADE_TIME_PATTERNS = listOf(
        Regex("(\\d{4})-(\\d{1,2})-(\\d{1,2})\\s+(\\d{1,2}):(\\d{2})(?::(\\d{2}))?"),
        Regex("(\\d{4})年(\\d{1,2})月(\\d{1,2})日\\s+(\\d{1,2}):(\\d{2})(?::(\\d{2}))?")
    )

    /** 订单号标签 */
    val ORDER_LABELS = listOf("订单号", "交易单号", "商户单号", "交易号", "流水号", "账单号", "业务交易号")

    /**
     * 订单号标签的**行内**出现形式。
     *
     * ⚠️ 真机实测：支付宝账单详情页并不给订单号单独一行，而是把它塞在别的值里 ——
     * `商品说明 充值:阿里云服务购买,业务交易号:CFP000000000000000000`。
     * 只按「标签 → 整行值」取会漏掉，必须再扫一遍行内标签。
     */
    val ORDER_LABEL_INLINE = Regex(
        "(业务交易号|交易单号|商户单号|订单号|交易号|流水号|账单号)[:：]?"
    )

    val ORDER_ID = Regex("[A-Za-z0-9]{12,}")

    /**
     * 日期时间串。
     *
     * ⚠️ **两种格式都要认**：支付宝写 `2026-10-15 23:14:43`，微信写 `2026年10月10日 14:01:42`
     * （都是真机原文）。只认前者会让微信详情页取不到交易时间，去重就退化成 2 分钟的金额兜底指纹。
     */
    val DATE_TIME = Regex(
        "\\d{4}[-/]\\d{1,2}[-/]\\d{1,2}\\s+\\d{1,2}:\\d{2}(?::\\d{2})?" +
            "|\\d{4}年\\d{1,2}月\\d{1,2}日\\s*\\d{1,2}:\\d{2}(?::\\d{2})?"
    )

    /** 收入侧兜底分类（支出侧兜底用 [CategoryCatalog.FALLBACK]） */
    const val INCOME_FALLBACK = "其他收入"

    /** 红包通道的落点：支出红包属于人情往来（商户名是领取人，平台分类也拿不到） */
    const val RED_PACKET_CATEGORY = "发红包"

    /** 分类表全部合法名称（一级 + 二级）：映射落点必须在这里面，分类名不允许游离在分类表外 */
}
