    /** 兜底分类（三档都没命中时用） */
    const val FALLBACK_EXPENSE = "其他"
    const val FALLBACK_INCOME = "其他收入"

    /**
     * 从 [keywordSource] 里找第一个命中的分类名（大小写不敏感、包含匹配）。
     *
     * 命中值必须落在分类表内，否则跳过该条继续找 —— 防止表里写了已下线的分类名
     * 把账目写到表外去。
     *
     * @return 分类名；没命中返回 null（调用方继续下一档候选，最后兜底）
     */
    fun lookup(keywordSource: String, isIncome: Boolean): String? {
        val text = keywordSource.trim()
        if (text.isEmpty()) return null
        val lower = text.lowercase()
        val table = if (isIncome) INCOME else EXPENSE
        for ((target, keywords) in table) {
            if (target !in catalogNames) continue
            if (keywords.any { lower.contains(it) }) return target
        }
        return null
    }

    /** 表里出现过的全部目标分类名（测试用：校验 ⊆ 分类表） */
    fun allTargets(): Set<String> = (EXPENSE + INCOME).map { it.first }.toSet()

    /** 表里全部 (关键词, 目标分类)，测试用来看同一关键词是否被多个分类认领 */
    fun allKeywords(): List<Pair<String, String>> =
        (EXPENSE + INCOME).flatMap { (target, keywords) -> keywords.map { it to target } }

    /** 分类表快照：lookup 每次调用都重建 Set 会拖慢批量导入 */
    private val catalogNames: Set<String> = CategoryCatalog.allNames().toSet()
